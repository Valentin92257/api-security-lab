BEGIN;
-- Учетная запись; регистрация и создание корзины атомарны.
CREATE TABLE users (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  login varchar(32) NOT NULL,
  name varchar(100) NOT NULL,
  email varchar(254) NOT NULL,
  password_hash varchar(255) NOT NULL,
  PRIMARY KEY (id),
  UNIQUE (login),
  UNIQUE (email),
  CHECK (id BETWEEN 1 AND 9007199254740991)
);
-- Каталог неизменяем внутри run и до сохранения отчета.
CREATE TABLE products (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  name varchar(120) NOT NULL,
  description text NOT NULL DEFAULT '',
  price bigint NOT NULL,
  published boolean NOT NULL DEFAULT false,
  PRIMARY KEY (id),
  CHECK (price BETWEEN 1 AND 1000000000),
  CHECK (length(description) <= 4000),
  CHECK (id BETWEEN 1 AND 9007199254740991)
);
-- Условия неизменяемы внутри run; used_count меняется при оформлении.
CREATE TABLE coupons (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  code varchar(32) NOT NULL,
  discount_percent integer NOT NULL,
  expires_at timestamptz NOT NULL,
  max_uses bigint NOT NULL,
  used_count bigint NOT NULL DEFAULT 0,
  PRIMARY KEY (id),
  UNIQUE (code),
  CHECK (discount_percent BETWEEN 1 AND 100),
  CHECK (max_uses > 0),
  CHECK (id BETWEEN 1 AND 9007199254740991)
);
-- Не более одной корзины на пользователя; наличие обеспечивает регистрация.
CREATE TABLE carts (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  user_id bigint NOT NULL,
  coupon_id bigint,
  revision bigint NOT NULL DEFAULT 0,
  updated_at timestamptz NOT NULL,
  PRIMARY KEY (id),
  UNIQUE (user_id),
  CHECK (revision BETWEEN 0 AND 9007199254740991),
  CHECK (id BETWEEN 1 AND 9007199254740991)
);
-- Позиции текущей корзины.
CREATE TABLE cart_items (
  cart_id bigint NOT NULL,
  product_id bigint NOT NULL,
  quantity integer NOT NULL,
  PRIMARY KEY (cart_id, product_id)
);
-- Неизменяемый эффект checkout, успешный ответ и погашение купона; один купон на заказ, отмен нет.
CREATE TABLE orders (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  user_id bigint NOT NULL,
  cart_id bigint NOT NULL,
  cart_revision bigint NOT NULL,
  status varchar(16) NOT NULL DEFAULT 'CREATED',
  subtotal bigint NOT NULL,
  discount bigint NOT NULL,
  total bigint NOT NULL,
  coupon_id bigint,
  created_at timestamptz NOT NULL,
  idempotency_key_hash bytea NOT NULL,
  request_fingerprint bytea NOT NULL,
  response_body jsonb NOT NULL,
  PRIMARY KEY (id),
  CHECK (status = 'CREATED'),
  CHECK (octet_length(idempotency_key_hash) = 32),
  CHECK (octet_length(request_fingerprint) = 32),
  CHECK (jsonb_typeof(response_body) = 'object'),
  CHECK (id BETWEEN 1 AND 9007199254740991)
);
-- Неизменяемые позиции заказа с ценой на момент оформления.
CREATE TABLE order_items (
  order_id bigint NOT NULL,
  product_id bigint NOT NULL,
  quantity integer NOT NULL,
  unit_price bigint NOT NULL,
  PRIMARY KEY (order_id, product_id)
);
ALTER TABLE carts ADD FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT;
ALTER TABLE carts ADD FOREIGN KEY (coupon_id) REFERENCES coupons (id) ON DELETE RESTRICT;
