-- PostgreSQL 17. Empty database, migration_owner only. No seed data.
BEGIN;
-- Учетная запись; регистрация и создание корзины атомарны.
CREATE TABLE users (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  login varchar(32) NOT NULL,
  name varchar(100) NOT NULL,
  email varchar(254) NOT NULL,
  password_hash varchar(255) NOT NULL,
  PRIMARY KEY (id),
  UNIQUE (login),
  UNIQUE (email),
  CHECK (id BETWEEN 1 AND 9007199254740991)
);
-- Текущий каталог; изменения цены увеличивают catalog_version.
CREATE TABLE products (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  name varchar(120) NOT NULL,
  description text NOT NULL DEFAULT '',
  price bigint NOT NULL,
  published boolean NOT NULL DEFAULT false,
  catalog_version bigint NOT NULL DEFAULT 1,
  PRIMARY KEY (id),
  CHECK (price BETWEEN 1 AND 1000000000),
  CHECK (catalog_version > 0),
  CHECK (length(description) <= 4000),
  CHECK (id BETWEEN 1 AND 9007199254740991)
);
-- Текущие условия; счетчик не меняет terms_version.
CREATE TABLE coupons (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  code varchar(32) NOT NULL,
  discount_percent integer NOT NULL,
  expires_at timestamptz NOT NULL,
  max_uses bigint NOT NULL,
  used_count bigint NOT NULL DEFAULT 0,
  terms_version bigint NOT NULL DEFAULT 1,
  PRIMARY KEY (id),
  UNIQUE (code),
  CHECK (discount_percent BETWEEN 1 AND 100),
  CHECK (max_uses > 0),
  CHECK (terms_version > 0),
  CHECK (id BETWEEN 1 AND 9007199254740991)
);
-- Не более одной корзины на пользователя; наличие обеспечивает регистрация.
CREATE TABLE carts (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  user_id bigint NOT NULL,
  coupon_id bigint,
  revision bigint NOT NULL DEFAULT 0,
  updated_at timestamptz NOT NULL,
  PRIMARY KEY (id),
  UNIQUE (user_id),
  CHECK (revision BETWEEN 0 AND 9007199254740991),
  CHECK (id BETWEEN 1 AND 9007199254740991)
);
-- Позиции текущей корзины.
CREATE TABLE cart_items (
  cart_id bigint NOT NULL,
  product_id bigint NOT NULL,
  quantity integer NOT NULL,
  PRIMARY KEY (cart_id, product_id)
);
-- Снимок расчета; не является независимым эталоном evaluator.
CREATE TABLE checkout_intents (
  id uuid NOT NULL,
  user_id bigint NOT NULL,
  cart_id bigint NOT NULL,
  cart_revision bigint NOT NULL,
  snapshot_version integer NOT NULL DEFAULT 1,
  snapshot jsonb NOT NULL,
  fingerprint bytea NOT NULL,
  created_at timestamptz NOT NULL,
  expires_at timestamptz NOT NULL,
  consumed_order_id bigint,
  PRIMARY KEY (id),
  CHECK (octet_length(fingerprint) = 32),
  CHECK (jsonb_typeof(snapshot) = 'object'),
  CHECK (snapshot_version = 1),
  CHECK (expires_at > created_at)
);
-- Неизменяемый эффект checkout, успешный ответ и погашение купона; один купон на заказ, отмен нет.
CREATE TABLE orders (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  user_id bigint NOT NULL,
  cart_id bigint NOT NULL,
  cart_revision bigint NOT NULL,
  intent_id uuid NOT NULL,
  status varchar(16) NOT NULL DEFAULT 'CREATED',
  subtotal bigint NOT NULL,
  discount bigint NOT NULL,
  total bigint NOT NULL,
  coupon_id bigint,
  coupon_code varchar(32),
  coupon_percent integer,
  coupon_expires_at timestamptz,
  coupon_terms_version bigint,
  created_at timestamptz NOT NULL,
  idempotency_key_hash bytea NOT NULL,
  request_fingerprint bytea NOT NULL,
  response_body jsonb NOT NULL,
  PRIMARY KEY (id),
  CHECK (status = 'CREATED'),
  CHECK (octet_length(idempotency_key_hash) = 32),
  CHECK (octet_length(request_fingerprint) = 32),
  CHECK (jsonb_typeof(response_body) = 'object'),
  CHECK (id BETWEEN 1 AND 9007199254740991)
);
-- Неизменяемые позиции; цена и название зафиксированы.
CREATE TABLE order_items (
  order_id bigint NOT NULL,
  product_id bigint NOT NULL,
  quantity integer NOT NULL,
  name_snapshot varchar(120) NOT NULL,
  unit_price bigint NOT NULL,
  catalog_version bigint NOT NULL,
  PRIMARY KEY (order_id, product_id)
);
ALTER TABLE carts ADD FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT;
ALTER TABLE carts ADD FOREIGN KEY (coupon_id) REFERENCES coupons (id) ON DELETE RESTRICT;
CREATE INDEX carts_idx_1 ON carts (coupon_id);
ALTER TABLE cart_items ADD FOREIGN KEY (cart_id) REFERENCES carts (id) ON DELETE CASCADE;
ALTER TABLE cart_items ADD FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE RESTRICT;
CREATE INDEX cart_items_idx_1 ON cart_items (product_id);
ALTER TABLE checkout_intents ADD FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT;
ALTER TABLE checkout_intents ADD FOREIGN KEY (cart_id) REFERENCES carts (id) ON DELETE RESTRICT;
ALTER TABLE checkout_intents ADD FOREIGN KEY (consumed_order_id) REFERENCES orders (id) ON DELETE RESTRICT;
CREATE INDEX checkout_intents_idx_1 ON checkout_intents (cart_id, cart_revision);
CREATE INDEX checkout_intents_idx_2 ON checkout_intents (user_id);
CREATE INDEX checkout_intents_idx_3 ON checkout_intents (consumed_order_id);
ALTER TABLE orders ADD FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT;
ALTER TABLE orders ADD FOREIGN KEY (cart_id) REFERENCES carts (id) ON DELETE RESTRICT;
ALTER TABLE orders ADD FOREIGN KEY (intent_id) REFERENCES checkout_intents (id) ON DELETE RESTRICT;
ALTER TABLE orders ADD FOREIGN KEY (coupon_id) REFERENCES coupons (id) ON DELETE RESTRICT;
CREATE INDEX orders_idx_1 ON orders (user_id, created_at DESC, id DESC);
CREATE INDEX orders_idx_2 ON orders (intent_id);
CREATE INDEX orders_idx_3 ON orders (cart_id, cart_revision);
CREATE INDEX orders_idx_4 ON orders (coupon_id);
CREATE INDEX orders_idx_5 ON orders (user_id, idempotency_key_hash);
ALTER TABLE order_items ADD FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE;
ALTER TABLE order_items ADD FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE RESTRICT;
CREATE INDEX order_items_idx_1 ON order_items (product_id);
COMMIT;
