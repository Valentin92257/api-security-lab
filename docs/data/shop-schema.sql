ALTER TABLE cart_items ADD FOREIGN KEY (cart_id) REFERENCES carts (id) ON DELETE CASCADE;
ALTER TABLE cart_items ADD FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE RESTRICT;
CREATE INDEX cart_items_idx_1 ON cart_items (product_id);
ALTER TABLE orders ADD FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT;
ALTER TABLE orders ADD FOREIGN KEY (cart_id) REFERENCES carts (id) ON DELETE RESTRICT;
ALTER TABLE orders ADD FOREIGN KEY (coupon_id) REFERENCES coupons (id) ON DELETE RESTRICT;
CREATE INDEX orders_idx_1 ON orders (user_id, created_at DESC, id DESC);
CREATE INDEX orders_idx_2 ON orders (cart_id, cart_revision);
CREATE INDEX orders_idx_3 ON orders (coupon_id);
CREATE INDEX orders_idx_4 ON orders (user_id, idempotency_key_hash);
ALTER TABLE order_items ADD FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE;
ALTER TABLE order_items ADD FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE RESTRICT;
CREATE INDEX order_items_idx_1 ON order_items (product_id);
COMMIT;
