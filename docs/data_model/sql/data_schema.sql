-- Общая схема API магазина (PostgreSQL). Одинакова для vulnerable и protected.
-- Соответствует docs/physical-model.dbml.
--
-- Здесь только структурные ограничения (PK, FK, UNIQUE, NOT NULL) и ограничения каталога.

CREATE TABLE users
(
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login         varchar(32)  NOT NULL UNIQUE,
    name          varchar(100) NOT NULL,
    email         varchar(256) NOT NULL UNIQUE,
    password_hash varchar(100) NOT NULL
);

CREATE TABLE products
(
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        varchar(120) NOT NULL,
    description text         NOT NULL,
    price       integer      NOT NULL CHECK (price > 0) -- рубли
);

CREATE TABLE coupons
(
    id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code             varchar(32) NOT NULL UNIQUE,
    discount_percent integer     NOT NULL CHECK (discount_percent BETWEEN 1 AND 100),
    expires_at       timestamptz NOT NULL,
    max_uses         integer     NOT NULL CHECK (max_uses > 0),
    used_count       integer     NOT NULL DEFAULT 0
);

CREATE TABLE carts
(
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    integer     NOT NULL UNIQUE REFERENCES users (id), -- одна корзина на пользователя
    coupon_id  integer REFERENCES coupons (id),                   -- выбранный купон (0..1)
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE cart_items
(
    cart_id    integer NOT NULL REFERENCES carts (id) ON DELETE CASCADE,
    product_id integer NOT NULL REFERENCES products (id),
    quantity   integer NOT NULL,
    PRIMARY KEY (cart_id, product_id)
);

CREATE TABLE orders
(
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id   integer     NOT NULL REFERENCES users (id),
    coupon_id  integer REFERENCES coupons (id), -- применённый купон (0..1)
    status     varchar(16) NOT NULL DEFAULT 'CREATED' CHECK (status IN ('CREATED', 'CANCELLED')),
    subtotal   integer     NOT NULL,            -- сумма quantity * unit_price по позициям
    discount   integer     NOT NULL DEFAULT 0,  -- floor(subtotal * discount_percent / 100)
    total      integer     NOT NULL,            -- subtotal - discount
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE order_items
(
    order_id   integer NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    product_id integer NOT NULL REFERENCES products (id),
    quantity   integer NOT NULL,
    unit_price integer NOT NULL, -- цена при оформлении
    PRIMARY KEY (order_id, product_id)
);